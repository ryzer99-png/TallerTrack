-- 1. Extensión para generación de UUIDs (normalmente ya viene activa en Supabase)
create extension if not exists pgcrypto;

-- 2. Tabla principal de órdenes de servicio
create table if not exists public.ordenes (
  id uuid primary key default gen_random_uuid(),
  numero_orden integer generated by default as identity (start with 4063 increment by 1) unique not null,
  fecha_ingreso timestamptz not null default now(),
  cliente_nombre text not null,
  cliente_telefono text not null,
  tipo_equipo text not null,
  accesorios text not null default 'Ninguno',
  falla_reportada text not null,
  observaciones text not null default 'Revisar y cotizar antes de reparar',
  estado text not null default 'Recibido'
    check (estado in ('Recibido', 'En Revisión', 'Por Aprobar', 'Reparado', 'Entregado')),
  costo_estimado numeric(12, 2) not null default 0,
  impresa boolean not null default false
);

-- 3. Índices para búsquedas rápidas en el mesón y para el módulo de impresión
create index if not exists idx_ordenes_numero_orden
  on public.ordenes (numero_orden desc);

create index if not exists idx_ordenes_estado
  on public.ordenes (estado);

create index if not exists idx_ordenes_fecha_ingreso
  on public.ordenes (fecha_ingreso desc);

-- Índice parcial muy liviano para que el servicio local de impresión consulte
-- únicamente los tickets pendientes por imprimir (impresa = false).
create index if not exists idx_ordenes_pendientes_impresion
  on public.ordenes (fecha_ingreso asc)
  where impresa = false;

-- 4. Habilitar Realtime en la tabla `ordenes`
-- Permite que el tablero del taller y la vista pública del cliente
-- reflejen cambios de estado o de impresión al instante sin recargar.
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'ordenes'
  ) then
    alter publication supabase_realtime add table public.ordenes;
  end if;
end $$;

-- 5. Seguridad a nivel de fila (Row Level Security - RLS)
alter table public.ordenes enable row level security;

-- Políticas pensadas para operación ágil en taller con la clave pública (anon key).
-- Nota: Si más adelante agregas autenticación de técnicos en Supabase Auth,
-- puedes restringir INSERT/UPDATE a `authenticated` manteniendo SELECT público
-- para la consulta del cliente por QR (/orden?id=...).

drop policy if exists "Permitir lectura de ordenes" on public.ordenes;
create policy "Permitir lectura de ordenes"
  on public.ordenes
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Permitir crear ordenes" on public.ordenes;
create policy "Permitir crear ordenes"
  on public.ordenes
  for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Permitir actualizar ordenes" on public.ordenes;
create policy "Permitir actualizar ordenes"
  on public.ordenes
  for update
  to anon, authenticated
  using (true)
  with check (true);

